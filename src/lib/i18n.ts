export function useT() {
  const { prefs } = useApp()
  const lang = langCodeFromLabel(prefs.language)

  const t = ((key: TKey) => DICTS[lang][key] ?? en[key]) as {
    (key: TKey): string
    tt: (ns: keyof typeof ES_DATA, id: string, field: string, fallback: string) => string
    te: (value: string) => string
    lang: LangCode
  }

  t.tt = (ns, id, field, fallback) => {
    if (lang !== 'es') return fallback
    return ES_DATA[ns]?.[id]?.[field] ?? fallback
  }
  t.te = (value: string) => (lang === 'es' ? ENUM_ES[value] ?? value : value)
  t.lang = lang

  return t
}
