/**
 * i18n: the shell chrome and every screen retranslate when the language preference changes.
 * `t(key)` covers UI chrome strings. `t.tt(namespace, id, field, fallback)` covers per-item
 * tweak/data text (name, description, tooltip…) keyed by the item's id from lib/mock.ts —
 * only Spanish overrides are stored here, English falls back to the value already in mock.ts.
 * `t.te(value)` covers small shared enum-like words (Impact, Risk, status labels, etc.).
 */
export type LangCode = 'en' | 'es'

/** `prefs.language` stores a full label like "Español (España)" — only the code matters here. */
export function langCodeFromLabel(label: string): LangCode {
  return label.startsWith('Español') ? 'es' : 'en'
}

